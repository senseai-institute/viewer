// Page chrome: top bar with navigation, the synthetic-data badge, and the shortcuts dialog.

export function el<K extends keyof HTMLElementTagNameMap>(tag: K, cls?: string, text?: string): HTMLElementTagNameMap[K] {
  const e = document.createElement(tag);
  if (cls) e.className = cls;
  if (text !== undefined) e.textContent = text;
  return e;
}

export interface ChromeOpts {
  run?: string;
  title?: string;
  synthetic?: boolean;
  current: "runs" | "replay" | "compare" | "incidents";
  share?: boolean; // read-only share view: no navigation to other runs
}

export function topbar(o: ChromeOpts): HTMLElement {
  const bar = el("header", "topbar");
  const brand = el("a", "brand");
  brand.href = o.share ? location.pathname : "/";
  brand.append(el("span", "brand-mark"), "SenseAI Viewer");
  bar.append(brand);
  if (!o.share) {
    const nav = el("nav");
    nav.setAttribute("aria-label", "Pages");
    const link = (id: ChromeOpts["current"], label: string, href: string) => {
      const a = el("a", undefined, label);
      a.href = href;
      if (o.current === id) a.setAttribute("aria-current", "page");
      nav.append(a);
    };
    link("runs", "Runs", "/");
    if (o.run) {
      const r = encodeURIComponent(o.run);
      link("replay", "Replay", `/replay/${r}`);
      link("compare", "Compare", `/compare/${r}`);
      link("incidents", "Incidents", `/incidents/${r}`);
    }
    bar.append(nav);
  }
  bar.append(el("span", "title", o.title ?? ""));
  if (o.share) bar.append(el("span", "badge teal", "shared · read-only"));
  if (o.synthetic) {
    const b = el("span", "badge warn", "synthetic data");
    b.title = "Illustrative synthetic data generated by senseai_viewer.sample_data; not a measurement.";
    bar.append(b);
  }
  return bar;
}

export function helpDialog(): HTMLDialogElement {
  const d = el("dialog");
  d.setAttribute("aria-label", "Keyboard shortcuts");
  const h = el("h2", undefined, "Keyboard shortcuts");
  h.style.marginTop = "0";
  const dl = el("dl", "keys");
  const rows: [string, string][] = [
    ["space", "play / pause"],
    ["← →", "step one tick (shift: 1 s)"],
    ["[ ]", "previous / next reflex fire"],
    ["1 – 7", "toggle events, frames, surprise, bearing, path cells, tracks, ground truth"],
    ["p", "next profile"],
    ["e", "jump to the nearest fire and read its explanation"],
    ["c", "colour-blind-safe scale"],
    ["?", "this help"],
  ];
  for (const [k, v] of rows) dl.append(el("dt", undefined, k), el("dd", undefined, v));
  const close = el("button", "btn", "Close");
  close.addEventListener("click", () => d.close());
  close.style.marginTop = "16px";
  d.append(h, dl, close);
  document.body.append(d);
  return d;
}

export function copyLink(url: string): Promise<boolean> {
  if (navigator.clipboard?.writeText) return navigator.clipboard.writeText(url).then(() => true, () => false);
  return Promise.resolve(false);
}
